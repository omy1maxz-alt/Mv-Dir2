/**
 * Dedicated YouTube Caption Service & Provider Abstraction
 * 
 * Implements server-side and client-safe YouTube caption retrieval with:
 * 1. Multi-tier caption provider fallback (InnerTube, watch page, timedtext mirrors, Invidious/Piped).
 * 2. Strict timestamp preservation and structured segment extraction.
 * 3. Automatic identification of authentic YouTube Closed Captions vs. unavailable captions.
 * 4. Structured error diagnostics for AI Studio iframe environments.
 */

export interface TimedCaptionSegment {
  start: number; // In seconds
  duration: number; // In seconds
  text: string;
}

export type YouTubeCaptionSource = 'youtube_cc' | 'gemini_transcription' | 'user_srt' | 'unavailable';

export type CaptionErrorCode = 
  | 'YOUTUBE_VIDEO_INVALID'
  | 'CAPTIONS_NOT_AVAILABLE'
  | 'CAPTIONS_RETRIEVAL_BLOCKED'
  | 'YOUTUBE_REQUEST_BLOCKED'
  | 'SERVER_RETRIEVAL_FAILED'
  | 'GEMINI_TRANSCRIPTION_FAILED'
  | 'AI_STUDIO_IFRAME_RESTRICTION';

export interface SubtitleTrackSummary {
  name: string;
  code: string;
  url: string;
  isAutoGenerated: boolean;
}

export interface YouTubeCaptionResponse {
  success: boolean;
  videoId: string;
  title?: string;
  source: YouTubeCaptionSource;
  language?: string;
  isAutoGenerated?: boolean;
  segments?: TimedCaptionSegment[];
  rawSrt?: string;
  requiresTranscription?: boolean;
  reason?: CaptionErrorCode;
  message?: string;
  duration?: number;
  thumbnailUrl?: string;
  availableTracks?: SubtitleTrackSummary[];
}

function decodeHtmlEntities(str: string): string {
  if (!str) return '';
  return str
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&#(\d+);/g, (_, dec) => String.fromCharCode(parseInt(dec, 10)))
    .replace(/&#x([0-9a-fA-F]+);/g, (_, hex) => String.fromCharCode(parseInt(hex, 16)));
}

export function msToSrtTimecode(ms: number): string {
  const h = Math.floor(ms / 3600000).toString().padStart(2, '0');
  const m = Math.floor((ms % 3600000) / 60000).toString().padStart(2, '0');
  const s = Math.floor((ms % 60000) / 1000).toString().padStart(2, '0');
  const ml = Math.floor(ms % 1000).toString().padStart(3, '0');
  return `${h}:${m}:${s},${ml}`;
}

export function segmentsToSrt(segments: TimedCaptionSegment[]): string {
  if (!segments || segments.length === 0) return '';
  return segments.map((seg, idx) => {
    const startMs = Math.round(seg.start * 1000);
    const endMs = Math.max(startMs + 500, Math.round((seg.start + seg.duration) * 1000));
    return `${idx + 1}\n${msToSrtTimecode(startMs)} --> ${msToSrtTimecode(endMs)}\n${seg.text.trim()}\n`;
  }).join('\n');
}

export function parseRawCaptionToSegments(rawContent: string): TimedCaptionSegment[] {
  if (!rawContent || !rawContent.trim()) return [];
  const trimmed = rawContent.trim();
  const segments: TimedCaptionSegment[] = [];

  // 1. YouTube timedtext XML format: <text start="1.5" dur="2.3">Sample text</text>
  if (trimmed.includes('<transcript') || trimmed.includes('<timedtext') || (trimmed.includes('<text ') && trimmed.includes('start='))) {
    const regex = /<text\s+start="([\d.]+)"(?:\s+dur="([\d.]+)")?[^>]*>([\s\S]*?)<\/text>/gi;
    let match;
    while ((match = regex.exec(trimmed)) !== null) {
      const start = parseFloat(match[1]) || 0;
      const duration = parseFloat(match[2]) || 2.0;
      const text = decodeHtmlEntities(match[3].replace(/<[^>]+>/g, '').trim());
      if (text) {
        segments.push({ start, duration, text });
      }
    }
    if (segments.length > 0) {
      return segments.sort((a, b) => a.start - b.start);
    }

    // Secondary XML format: <p t="1500" d="2300">Sample</p>
    const pRegex = /<p\s+t="(\d+)"(?:\s+d="(\d+)")?[^>]*>([\s\S]*?)<\/p>/gi;
    while ((match = pRegex.exec(trimmed)) !== null) {
      const startMs = parseInt(match[1], 10) || 0;
      const durMs = parseInt(match[2], 10) || 2000;
      const text = decodeHtmlEntities(match[3].replace(/<[^>]+>/g, '').trim());
      if (text) {
        segments.push({ start: startMs / 1000, duration: durMs / 1000, text });
      }
    }
    if (segments.length > 0) {
      return segments.sort((a, b) => a.start - b.start);
    }
  }

  // 2. YouTube JSON3 format
  if (trimmed.startsWith('{') && trimmed.includes('"events"')) {
    try {
      const parsed = JSON.parse(trimmed);
      if (Array.isArray(parsed.events)) {
        for (const ev of parsed.events) {
          if (typeof ev.tStartMs === 'number' && Array.isArray(ev.segs)) {
            const start = ev.tStartMs / 1000;
            const duration = (typeof ev.dDurationMs === 'number' ? ev.dDurationMs : 2000) / 1000;
            const text = ev.segs.map((s: any) => s.utf8 || '').join('').trim();
            if (text && text !== '\n') {
              segments.push({ start, duration, text: decodeHtmlEntities(text) });
            }
          }
        }
        if (segments.length > 0) {
          return segments.sort((a, b) => a.start - b.start);
        }
      }
    } catch (_) {}
  }

  // 3. WebVTT / SRT format
  const normalized = trimmed.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const chunks = normalized.split(/\n\n+/);
  for (const chunk of chunks) {
    const lines = chunk.trim().split('\n');
    let timeIdx = -1;
    for (let i = 0; i < lines.length; i++) {
      if (lines[i].includes('-->')) {
        timeIdx = i;
        break;
      }
    }
    if (timeIdx === -1) continue;
    const [startStr, endStr] = lines[timeIdx].split('-->').map(s => s.trim().split(/\s+/)[0]);
    const textLines = lines.slice(timeIdx + 1);
    const text = decodeHtmlEntities(textLines.join('\n').trim());
    if (startStr && endStr && text) {
      const startSec = timeToSeconds(startStr);
      const endSec = timeToSeconds(endStr);
      const duration = Math.max(0.5, endSec - startSec);
      segments.push({ start: startSec, duration, text });
    }
  }

  return segments.sort((a, b) => a.start - b.start);
}

function timeToSeconds(str: string): number {
  const clean = str.trim().replace(',', '.');
  const parts = clean.split(':');
  if (parts.length === 3) {
    return parseFloat(parts[0]) * 3600 + parseFloat(parts[1]) * 60 + parseFloat(parts[2]);
  } else if (parts.length === 2) {
    return parseFloat(parts[0]) * 60 + parseFloat(parts[1]);
  }
  return parseFloat(parts[0]) || 0;
}
