/**
 * Dedicated YouTube Caption Service & Provider Abstraction
 * Ported and aligned with Mydownloader's SubtitleUtils.kt & YoutubeExtractorHelper.kt:
 * 1. Supports TTML (<tt><p begin="..." end="...">), SRV1 (<text start="..." dur="...">),
 *    SRV2/SRV3 (<p t="..." d="..."><s>...</s></p>), JSON3, WebVTT, and SRT.
 * 2. Attribute-order-independent XML/TTML timestamp parsing (clock HH:MM:SS.mmm, ms, s, m, h).
 * 3. Strips YouTube dialogue speaker markers (">>") while preserving multi-line (<br/>) cues.
 * 4. Parses HLS master playlist #EXT-X-MEDIA:TYPE=SUBTITLES tracks and merges WebVTT segments
 *    with X-TIMESTAMP-MAP MPEGTS offset alignment.
 */

export interface TimedCaptionSegment {
  start: number; // In seconds
  duration: number; // In seconds
  end?: number; // Optional end in seconds
  text: string;
}

export type CaptionSegment = TimedCaptionSegment;

export type YouTubeCaptionSource =
  | 'youtube_cc'
  | 'gemini_transcription'
  | 'user_srt'
  | 'unavailable';

export type CaptionErrorCode =
  | 'YOUTUBE_VIDEO_INVALID'
  | 'CAPTIONS_NOT_AVAILABLE'
  | 'CAPTIONS_RETRIEVAL_BLOCKED'
  | 'YOUTUBE_REQUEST_BLOCKED'
  | 'SERVER_RETRIEVAL_FAILED'
  | 'GEMINI_TRANSCRIPTION_FAILED'
  | 'AI_STUDIO_IFRAME_RESTRICTION';

export interface SubtitleTrackSummary {
  name: string;
  code: string;
  url: string;
  isAutoGenerated: boolean;
}

export interface YouTubeCaptionResponse {
  success: boolean;
  videoId: string;
  title?: string;
  source: YouTubeCaptionSource;
  language?: string;
  languageCode?: string;
  isAutoGenerated?: boolean;
  segments?: TimedCaptionSegment[];
  rawSrt?: string;
  rawVtt?: string;
  requiresTranscription?: boolean;
  reason?: CaptionErrorCode | string;
  message?: string;
  duration?: number;
  thumbnailUrl?: string;
  availableTracks?: SubtitleTrackSummary[];
  availableLanguages?: Array<{ code: string; name: string; isAuto: boolean }>;
}

export type CaptionServiceResponse = YouTubeCaptionResponse;

function decodeHtmlEntities(str: string): string {
  if (!str) return '';
  return str
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&nbsp;/g, ' ')
    .replace(/&#160;/g, ' ')
    .replace(/&#(\d+);/g, (_, dec) => String.fromCharCode(parseInt(dec, 10)))
    .replace(/&#x([0-9a-fA-F]+);/g, (_, hex) => String.fromCharCode(parseInt(hex, 16)));
}

function cleanSpeakerMarkers(text: string): string {
  return text
    .split('\n')
    .map((line) => line.replace(/^\s*>>\s*/, '').trim())
    .filter(Boolean)
    .join('\n');
}

export function msToSrtTimecode(ms: number): string {
  const safe = Math.max(0, Math.round(ms));
  const h = Math.floor(safe / 3600000)
    .toString()
    .padStart(2, '0');
  const m = Math.floor((safe % 3600000) / 60000)
    .toString()
    .padStart(2, '0');
  const s = Math.floor((safe % 60000) / 1000)
    .toString()
    .padStart(2, '0');
  const ml = Math.floor(safe % 1000)
    .toString()
    .padStart(3, '0');
  return `${h}:${m}:${s},${ml}`;
}

export function msToVttTimecode(ms: number): string {
  const safe = Math.max(0, Math.round(ms));
  const h = Math.floor(safe / 3600000)
    .toString()
    .padStart(2, '0');
  const m = Math.floor((safe % 3600000) / 60000)
    .toString()
    .padStart(2, '0');
  const s = Math.floor((safe % 60000) / 1000)
    .toString()
    .padStart(2, '0');
  const ml = Math.floor(safe % 1000)
    .toString()
    .padStart(3, '0');
  return `${h}:${m}:${s}.${ml}`;
}

function resolveSegmentEndSeconds(seg: TimedCaptionSegment): number {
  const start = Number(seg.start) || 0;
  if (typeof seg.duration === 'number' && !isNaN(seg.duration) && seg.duration > 0) {
    return start + seg.duration;
  }
  if (typeof seg.end === 'number' && !isNaN(seg.end) && seg.end > start) {
    return seg.end;
  }
  return start + 2.0;
}

export function segmentsToSrt(segments: TimedCaptionSegment[]): string {
  if (!segments || segments.length === 0) return '';
  return segments
    .map((seg, idx) => {
      const startMs = Math.round((Number(seg.start) || 0) * 1000);
      const endMs = Math.max(startMs + 400, Math.round(resolveSegmentEndSeconds(seg) * 1000));
      return `${idx + 1}\n${msToSrtTimecode(startMs)} --> ${msToSrtTimecode(endMs)}\n${seg.text.trim()}\n`;
    })
    .join('\n');
}

export function segmentsToVtt(segments: TimedCaptionSegment[]): string {
  if (!segments || segments.length === 0) return 'WEBVTT\n\n';
  const body = segments
    .map((seg) => {
      const startMs = Math.round((Number(seg.start) || 0) * 1000);
      const endMs = Math.max(startMs + 400, Math.round(resolveSegmentEndSeconds(seg) * 1000));
      return `${msToVttTimecode(startMs)} --> ${msToVttTimecode(endMs)}\n${seg.text.trim()}`;
    })
    .join('\n\n');
  return `WEBVTT\n\n${body}\n`;
}

/**
 * Ported from Mydownloader SubtitleUtils.kt `timeToMillis`:
 * Parses clock timestamps (HH:MM:SS.mmm or MM:SS.mmm), unit timestamps (1500ms, 1.5s, 2m, 1h),
 * or raw numeric strings (seconds vs milliseconds).
 */
function xmlTimeToMillis(value: string, defaultUnit: 'seconds' | 'milliseconds'): number | null {
  const time = (value || '').trim();
  if (!time) return null;

  const clock3 = time.match(/^(\d{1,3}):(\d{2}):(\d{2})(?:[.,](\d+))?$/);
  if (clock3) {
    const hh = parseInt(clock3[1], 10);
    const mm = parseInt(clock3[2], 10);
    const ss = parseInt(clock3[3], 10);
    const ms = clock3[4] ? parseInt(clock3[4].padEnd(3, '0').slice(0, 3), 10) : 0;
    return ((hh * 60 + mm) * 60 + ss) * 1000 + ms;
  }

  const clock2 = time.match(/^(\d{1,2}):(\d{2})(?:[.,](\d+))?$/);
  if (clock2) {
    const mm = parseInt(clock2[1], 10);
    const ss = parseInt(clock2[2], 10);
    const ms = clock2[3] ? parseInt(clock2[3].padEnd(3, '0').slice(0, 3), 10) : 0;
    return (mm * 60 + ss) * 1000 + ms;
  }

  const withUnit = time.match(/^(\d+(?:\.\d+)?)(ms|s|m|h|t)$/i);
  if (withUnit) {
    const amount = parseFloat(withUnit[1]);
    if (!isFinite(amount)) return null;
    const unit = withUnit[2].toLowerCase();
    const factor =
      unit === 'ms'
        ? 1
        : unit === 'm'
          ? 60000
          : unit === 'h'
            ? 3600000
            : unit === 't'
              ? 0.0001
              : 1000;
    return Math.round(amount * factor);
  }

  const numeric = parseFloat(time);
  if (!isFinite(numeric) || numeric < 0) return null;
  return Math.round(numeric * (defaultUnit === 'milliseconds' ? 1 : 1000));
}

function readXmlAttr(attrs: string, name: string): string | null {
  const regex = new RegExp(`\\b${name}\\s*=\\s*["']([^"']+)["']`, 'i');
  const m = attrs.match(regex);
  return m ? m[1] : null;
}

export function parseRawCaptionToSegments(rawContent: string): TimedCaptionSegment[] {
  if (!rawContent || !rawContent.trim()) return [];
  const trimmed = rawContent.trim().replace(/^\uFEFF/, '').trim();
  const lower = trimmed.toLowerCase();
  const segments: TimedCaptionSegment[] = [];

  // 1. YouTube JSON3 format: {"events":[{"tStartMs":1500,"dDurationMs":2300,"segs":[{"utf8":"Hello"}]}]}
  if (trimmed.startsWith('{') && trimmed.includes('"events"')) {
    try {
      const parsed = JSON.parse(trimmed);
      if (Array.isArray(parsed.events)) {
        for (const ev of parsed.events) {
          if (typeof ev.tStartMs === 'number' && Array.isArray(ev.segs)) {
            const start = ev.tStartMs / 1000;
            const duration =
              (typeof ev.dDurationMs === 'number' && ev.dDurationMs > 0 ? ev.dDurationMs : 2000) /
              1000;
            const rawText = ev.segs.map((s: any) => s.utf8 || '').join('');
            const text = cleanSpeakerMarkers(decodeHtmlEntities(rawText).trim());
            if (text && text !== '\n') {
              segments.push({ start, duration, end: start + duration, text });
            }
          }
        }
        if (segments.length > 0) {
          return segments.sort((a, b) => a.start - b.start);
        }
      }
    } catch {
      // fall through
    }
  }

  // 2. YouTube XML / TTML / SRV1 / SRV2 / SRV3 formats (ported from Mydownloader SubtitleUtils.kt)
  const isCaptionXml =
    lower.startsWith('<tt') ||
    lower.startsWith('<?xml') ||
    lower.startsWith('<transcript') ||
    lower.startsWith('<timedtext') ||
    /<(?:text|p)\b[^>]*(?:\bstart=|\bbegin=|\bt=)/i.test(trimmed);

  if (isCaptionXml) {
    const cueRegex = /<(p|text)\b([^>]*)>([\s\S]*?)<\/\1\s*>/gi;
    let match: RegExpExecArray | null;
    while ((match = cueRegex.exec(trimmed)) !== null) {
      const attrs = match[2];
      const innerHtml = match[3];

      const begin = readXmlAttr(attrs, 'begin');
      const startSeconds = readXmlAttr(attrs, 'start');
      const startTicks = readXmlAttr(attrs, 't');
      const startValue = begin ?? startSeconds ?? startTicks;
      if (startValue === null) continue;

      const startMillis = xmlTimeToMillis(
        startValue,
        startTicks !== null && begin === null && startSeconds === null ? 'milliseconds' : 'seconds'
      );
      if (startMillis === null) continue;

      const explicitEnd = readXmlAttr(attrs, 'end');
      const durationSeconds = readXmlAttr(attrs, 'dur');
      const durationTicks = readXmlAttr(attrs, 'd');

      let endMillis: number | null = null;
      if (explicitEnd !== null) {
        endMillis = xmlTimeToMillis(explicitEnd, 'seconds');
      } else if (durationSeconds !== null) {
        const d = xmlTimeToMillis(durationSeconds, 'seconds');
        if (d !== null) endMillis = startMillis + d;
      } else if (durationTicks !== null) {
        const d = xmlTimeToMillis(durationTicks, 'milliseconds');
        if (d !== null) endMillis = startMillis + d;
      } else {
        endMillis = startMillis + 2000;
      }

      if (endMillis === null || endMillis <= startMillis) {
        endMillis = startMillis + 1500;
      }

      const rawText = innerHtml
        .replace(/<br\s*\/?>/gi, '\n')
        .replace(/<[^>]+>/g, '');
      const text = cleanSpeakerMarkers(decodeHtmlEntities(rawText).trim());
      if (text) {
        const startSec = startMillis / 1000;
        const durSec = Math.max(0.4, (endMillis - startMillis) / 1000);
        segments.push({
          start: startSec,
          duration: durSec,
          end: startSec + durSec,
          text,
        });
      }
    }

    if (segments.length > 0) {
      return segments.sort((a, b) => a.start - b.start);
    }
  }

  // 3. WebVTT / SRT format
  const normalized = trimmed.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const chunks = normalized.split(/\n\n+/);
  for (const chunk of chunks) {
    const lines = chunk.trim().split('\n');
    let timeIdx = -1;
    for (let i = 0; i < lines.length; i++) {
      if (lines[i].includes('-->')) {
        timeIdx = i;
        break;
      }
    }
    if (timeIdx === -1) continue;
    const [startStr, endStr] = lines[timeIdx]
      .split('-->')
      .map((s) => s.trim().split(/\s+/)[0]);
    const textLines = lines.slice(timeIdx + 1);
    const text = cleanSpeakerMarkers(decodeHtmlEntities(textLines.join('\n').trim()));
    if (startStr && endStr && text) {
      const startSec = timeToSeconds(startStr);
      const endSec = timeToSeconds(endStr);
      const duration = Math.max(0.4, endSec - startSec);
      segments.push({ start: startSec, duration, end: startSec + duration, text });
    }
  }

  return segments.sort((a, b) => a.start - b.start);
}

function timeToSeconds(str: string): number {
  const clean = str.trim().replace(',', '.');
  const parts = clean.split(':');
  if (parts.length === 3) {
    return parseFloat(parts[0]) * 3600 + parseFloat(parts[1]) * 60 + parseFloat(parts[2]);
  } else if (parts.length === 2) {
    return parseFloat(parts[0]) * 60 + parseFloat(parts[1]);
  }
  return parseFloat(parts[0]) || 0;
}

/**
 * Ported from Mydownloader SubtitleUtils.kt `parseSubtitleTracks`:
 * Extracts #EXT-X-MEDIA:TYPE=SUBTITLES tracks from a YouTube HLS master .m3u8 manifest.
 */
export interface HlsSubtitleTrack {
  uri: string;
  language: string;
  name: string;
  isDefault: boolean;
}

export function parseHlsMasterSubtitleTracks(
  masterPlaylist: string,
  masterBaseUrl: string
): HlsSubtitleTrack[] {
  const out: HlsSubtitleTrack[] = [];
  if (!masterPlaylist) return out;
  const lines = masterPlaylist.replace(/\r\n/g, '\n').split('\n');

  const readAttr = (tag: string, key: string): string | null => {
    const regex = new RegExp(`${key}="([^"]+)"`, 'i');
    const m = tag.match(regex);
    return m ? m[1] : null;
  };

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (line.startsWith('#EXT-X-MEDIA:') && /TYPE=SUBTITLES/i.test(line)) {
      const uri = readAttr(line, 'URI');
      if (!uri) continue;
      const language = (readAttr(line, 'LANGUAGE') || 'en').toLowerCase();
      const name = readAttr(line, 'NAME') || language;
      const isDefault = (readAttr(line, 'DEFAULT') || '').toUpperCase() === 'YES';
      try {
        const absUri = new URL(uri, masterBaseUrl).toString();
        out.push({ uri: absUri, language, name, isDefault });
      } catch {
        // ignore invalid URI
      }
    }
  }
  return out;
}

/**
 * Ported from Mydownloader SubtitleUtils.kt `parseHlsSubtitlePlaylistUris`:
 * Resolves WebVTT segment URIs inside an HLS subtitle media playlist.
 */
export function parseHlsSubtitlePlaylistUris(playlist: string, playlistUrl: string): string[] {
  const lines = (playlist || '').replace(/\r\n/g, '\n').split('\n');
  const uris: string[] = [];
  for (const raw of lines) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    try {
      uris.push(new URL(line, playlistUrl).toString());
    } catch {
      // ignore
    }
  }
  return uris.slice(0, 400);
}
