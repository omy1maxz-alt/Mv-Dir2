export async function resolveYouTubeVideoServerSide(videoId: string) {
  let title = 'YouTube_Video';
  let dashUrl: string | null = null;
  let hlsUrl: string | null = null;
  let combinedStreamUrl: string | null = null;
  let combinedQuality: string | null = null;
  let bestAudioUrl: string | null = null;
  let audioBitrate: number | null = null;
  let bestVideoOnlyUrl: string | null = null;
  let videoQuality: string | null = null;
  let duration = 0;
  let thumbnailUrl = `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`;

  // Fetch watch/embed context + oEmbed metadata in parallel
  const [ctx, oembedMeta] = await Promise.all([
    fetchWatchAndEmbedContext(videoId),
    (async () => {
      const controller = new AbortController();
      const timer = setTimeout(() => controller.abort(), 3000);
      try {
        const res = await fetch(
          `https://www.youtube.com/oembed?url=https://www.youtube.com/watch?v=${videoId}&format=json`,
          { signal: controller.signal }
        );
        if (res.ok) return await res.json();
      } catch {
        // ignore
      } finally {
        clearTimeout(timer);
      }
      return null;
    })(),
  ]);

  if (ctx.title) title = ctx.title;
  else if (oembedMeta?.title) title = oembedMeta.title;

  // Query all InnerTube clients concurrently
  const playerPayloads = await fetchYouTubePlayerDataCandidates(videoId, ctx);
  let subtitles = collectYouTubeCaptionTracks(playerPayloads, ctx.captionTracks);

  const discoveredFormats: StreamFormatItem[] = [];
  const seenFormatKeys = new Set<string>();

  const pushFormat = (item: StreamFormatItem) => {
    const key = `${item.type}|${item.quality || item.label}|${item.mimeType.split(';')[0]}`;
    if (seenFormatKeys.has(key)) return;
    seenFormatKeys.add(key);
    discoveredFormats.push(item);
  };

  for (const data of playerPayloads) {
    if (data?.videoDetails) {
      if (data.videoDetails.title && title === 'YouTube_Video') title = data.videoDetails.title;
      if (data.videoDetails.lengthSeconds && !duration) {
        duration = parseInt(data.videoDetails.lengthSeconds, 10) || 0;
      }
      const thumbs = data.videoDetails.thumbnail?.thumbnails;
      if (Array.isArray(thumbs) && thumbs.length > 0) {
        thumbnailUrl = thumbs[thumbs.length - 1].url || thumbnailUrl;
      }
    }

    const sd = data?.streamingData;
    if (!sd) continue;

    if (sd.dashManifestUrl && !dashUrl) dashUrl = sd.dashManifestUrl;
    if (sd.hlsManifestUrl && !hlsUrl) hlsUrl = sd.hlsManifestUrl;

    if (Array.isArray(sd.formats)) {
      const sortedComb = [...sd.formats]
        .filter((f: any) => f?.url)
        .sort((a: any, b: any) => (b.height || 0) - (a.height || 0));

      for (const f of sortedComb) {
        const q = f.qualityLabel || `${f.height || 360}p`;
        const proxiedUrl = `/api/youtube/stream?videoId=${encodeURIComponent(videoId)}&quality=${encodeURIComponent(q)}&url=${encodeURIComponent(f.url)}`;
        pushFormat({
          id: `it-comb-${f.itag || q}`,
          type: 'combined',
          label: `MP4 Video + Audio (${q})`,
          quality: q,
          bitrate: f.bitrate,
          mimeType: f.mimeType || 'video/mp4',
          url: proxiedUrl,
          directUrl: f.url,
          isProxyUrl: true,
        });
      }

      if (sortedComb.length > 0 && !combinedStreamUrl) {
        combinedStreamUrl = sortedComb[0].url;
        combinedQuality = sortedComb[0].qualityLabel || `${sortedComb[0].height || 720}p`;
      }
    }

    if (Array.isArray(sd.adaptiveFormats)) {
      const audioFormats = sd.adaptiveFormats
        .filter((f: any) => f?.url && f.mimeType?.startsWith('audio/'))
        .sort((a: any, b: any) => (b.bitrate || 0) - (a.bitrate || 0));

      for (const f of audioFormats) {
        const kbps = f.bitrate ? Math.round(f.bitrate / 1000) : 128;
        const ext = f.mimeType?.includes('mp4') ? 'M4A' : 'WEBM';
        const proxiedUrl = `/api/youtube/stream?videoId=${encodeURIComponent(videoId)}&quality=audio&url=${encodeURIComponent(f.url)}`;
        pushFormat({
          id: `it-audio-${f.itag || kbps}`,
          type: 'audio',
          label: `Audio Only (${ext} • ${kbps} kbps)`,
          quality: `${kbps}kbps`,
          bitrate: f.bitrate,
          mimeType: f.mimeType || 'audio/mp4',
          url: proxiedUrl,
          directUrl: f.url,
          isProxyUrl: true,
        });
      }

      if (audioFormats.length > 0 && !bestAudioUrl) {
        bestAudioUrl = audioFormats[0].url;
        audioBitrate = audioFormats[0].bitrate || null;
      }

      const videoFormats = sd.adaptiveFormats
        .filter((f: any) => f?.url && f.mimeType?.startsWith('video/'))
        .sort((a: any, b: any) => (b.height || 0) - (a.height || 0));

      for (const f of videoFormats.slice(0, 6)) {
        const q = f.qualityLabel || `${f.height || 720}p`;
        const proxiedUrl = `/api/youtube/stream?videoId=${encodeURIComponent(videoId)}&quality=${encodeURIComponent(q)}&url=${encodeURIComponent(f.url)}`;
        pushFormat({
          id: `it-vid-${f.itag || q}`,
          type: 'video',
          label: `Adaptive Video (${q})`,
          quality: q,
          bitrate: f.bitrate,
          mimeType: f.mimeType || 'video/mp4',
          url: proxiedUrl,
          directUrl: f.url,
          isProxyUrl: true,
        });
      }

      if (videoFormats.length > 0 && !bestVideoOnlyUrl) {
        bestVideoOnlyUrl = videoFormats[0].url;
        videoQuality = videoFormats[0].qualityLabel || `${videoFormats[0].height || 1080}p`;
      }
    }
  }

  // Step 2: Parallel Piped + Invidious + Cobalt fallback if direct formats or captions are still empty
  if (discoveredFormats.length === 0 || subtitles.length === 0) {
    const mirrorTasks: Promise<void>[] = [];

    for (const piped of PIPED_INSTANCES) {
      mirrorTasks.push(
        (async () => {
          const controller = new AbortController();
          const timer = setTimeout(() => controller.abort(), 4500);
          try {
            const res = await fetch(`${piped}/streams/${videoId}`, {
              headers: { Accept: 'application/json', 'User-Agent': DESKTOP_CHROME_UA },
              signal: controller.signal,
            });
            if (!res.ok) return;
            const data = await res.json();
            if (data.title && title === 'YouTube_Video') title = data.title;
            if (data.duration && !duration) duration = data.duration;
            if (data.thumbnailUrl) thumbnailUrl = data.thumbnailUrl;
            if (data.hls && !hlsUrl) hlsUrl = data.hls;
            if (data.dash && !dashUrl) dashUrl = data.dash;

            if (Array.isArray(data.subtitles) && subtitles.length === 0) {
              subtitles = data.subtitles
                .filter((s: any) => s?.url)
                .map((s: any) => ({
                  name: s.name || s.code || 'Subtitles',
                  code: s.code || 'en',
                  url: s.url,
                  isAutoGenerated: Boolean(s.autoGenerated),
                  mimeType: s.mimeType || 'text/vtt',
                }));
            }

            if (Array.isArray(data.audioStreams)) {
              const sortedAudio = [...data.audioStreams]
                .filter((s: any) => s?.url)
                .sort((a: any, b: any) => (b.bitrate || 0) - (a.bitrate || 0));
              for (const a of sortedAudio.slice(0, 4)) {
                const kbps = a.bitrate ? Math.round(a.bitrate / 1000) : 128;
                pushFormat({
                  id: `piped-audio-${kbps}-${Math.random().toString(36).slice(2, 6)}`,
                  type: 'audio',
                  label: `Audio Stream (${a.format || 'M4A'} • ${a.quality || kbps + 'kbps'})`,
                  quality: a.quality || `${kbps}kbps`,
                  bitrate: a.bitrate,
                  mimeType: a.mimeType || 'audio/mp4',
                  url: `/api/youtube/stream?videoId=${encodeURIComponent(videoId)}&quality=audio&url=${encodeURIComponent(a.url)}`,
                  directUrl: a.url,
                  isProxyUrl: true,
                });
              }
              if (sortedAudio.length > 0 && !bestAudioUrl) {
                bestAudioUrl = sortedAudio[0].url;
                audioBitrate = sortedAudio[0].bitrate || null;
              }
            }

            if (Array.isArray(data.videoStreams)) {
              const muxed = data.videoStreams.filter((s: any) => s?.url && s.videoOnly === false);
              for (const v of muxed) {
                pushFormat({
                  id: `piped-comb-${v.quality || '720p'}`,
                  type: 'combined',
                  label: `Video + Audio (${v.quality || '720p'})`,
                  quality: v.quality || '720p',
                  mimeType: v.mimeType || 'video/mp4',
                  url: `/api/youtube/stream?videoId=${encodeURIComponent(videoId)}&quality=720&url=${encodeURIComponent(v.url)}`,
                  directUrl: v.url,
                  isProxyUrl: true,
                });
              }
              if (muxed.length > 0 && !combinedStreamUrl) {
                combinedStreamUrl = muxed[0].url;
                combinedQuality = muxed[0].quality || '720p';
              }
            }
          } catch {
            // ignore
          } finally {
            clearTimeout(timer);
          }
        })()
      );
    }

    for (const inv of INVIDIOUS_INSTANCES) {
      mirrorTasks.push(
        (async () => {
          const controller = new AbortController();
          const timer = setTimeout(() => controller.abort(), 4500);
          try {
            const res = await fetch(`${inv}/api/v1/videos/${videoId}`, {
              headers: { Accept: 'application/json', 'User-Agent': DESKTOP_CHROME_UA },
              signal: controller.signal,
            });
            if (!res.ok) return;
            const data = await res.json();
            if (data.title && title === 'YouTube_Video') title = data.title;
            if (data.lengthSeconds && !duration) duration = data.lengthSeconds;
            if (data.hlsUrl && !hlsUrl) hlsUrl = data.hlsUrl;
            if (data.dashUrl && !dashUrl) {
              dashUrl = data.dashUrl.startsWith('http') ? data.dashUrl : `${inv}${data.dashUrl}`;
            }

            if (Array.isArray(data.captions) && subtitles.length === 0) {
              subtitles = data.captions
                .filter((c: any) => c?.url)
                .map((c: any) => ({
                  name: c.label || c.language_code || 'Subtitles',
                  code: c.language_code || 'en',
                  url: c.url.startsWith('http') ? c.url : `${inv}${c.url}`,
                  isAutoGenerated: Boolean(String(c.label || '').toLowerCase().includes('auto')),
                  mimeType: 'text/vtt',
                }));
            }

            if (Array.isArray(data.formatStreams)) {
              for (const f of data.formatStreams) {
                if (!f?.url) continue;
                const q = f.qualityLabel || '360p';
                // Invidious supports ?local=true to proxy the stream through the Invidious instance
                const invLocalUrl = `${inv}/latest_version?id=${videoId}&itag=${f.itag || 18}&local=true`;
                pushFormat({
                  id: `inv-comb-${f.itag || q}`,
                  type: 'combined',
                  label: `MP4 Video + Audio (${q} • Mirror)`,
                  quality: q,
                  mimeType: f.type || 'video/mp4',
                  url: `/api/youtube/stream?videoId=${encodeURIComponent(videoId)}&quality=${encodeURIComponent(q)}&url=${encodeURIComponent(invLocalUrl)}`,
                  directUrl: invLocalUrl,
                  isProxyUrl: true,
                });
                if (!combinedStreamUrl) {
                  combinedStreamUrl = invLocalUrl;
                  combinedQuality = q;
                }
              }
            }

            if (Array.isArray(data.adaptiveFormats)) {
              const audios = data.adaptiveFormats.filter(
                (f: any) => f?.url && f.type?.startsWith('audio/')
              );
              for (const a of audios.slice(0, 3)) {
                const kbps = a.bitrate ? Math.round(parseInt(a.bitrate, 10) / 1000) : 128;
                const rawUrl = a.url.startsWith('http') ? a.url : `${inv}${a.url}`;
                pushFormat({
                  id: `inv-audio-${a.itag || kbps}`,
                  type: 'audio',
                  label: `Audio Stream (${kbps}kbps)`,
                  quality: `${kbps}kbps`,
                  bitrate: parseInt(a.bitrate || '128000', 10),
                  mimeType: a.type || 'audio/mp4',
                  url: `/api/youtube/stream?videoId=${encodeURIComponent(videoId)}&quality=audio&url=${encodeURIComponent(rawUrl)}`,
                  directUrl: rawUrl,
                  isProxyUrl: true,
                });
                if (!bestAudioUrl) {
                  bestAudioUrl = rawUrl;
                  audioBitrate = parseInt(a.bitrate || '128000', 10);
                }
              }
            }
          } catch {
            // ignore
          } finally {
            clearTimeout(timer);
          }
        })()
      );
    }

    for (const cobaltBase of COBALT_INSTANCES) {
      mirrorTasks.push(
        (async () => {
          const controller = new AbortController();
          const timer = setTimeout(() => controller.abort(), 4500);
          try {
            const res = await fetch(`${cobaltBase}/`, {
              method: 'POST',
              headers: {
                Accept: 'application/json',
                'Content-Type': 'application/json',
                'User-Agent': DESKTOP_CHROME_UA,
              },
              body: JSON.stringify({
                url: `https://www.youtube.com/watch?v=${videoId}`,
                videoQuality: '720',
                downloadMode: 'auto',
              }),
              signal: controller.signal,
            });
            if (!res.ok) return;
            const data = await res.json();
            if (data?.url) {
              pushFormat({
                id: `cobalt-720-${videoId}`,
                type: 'combined',
                label: '720p HD Video + Audio (Cobalt Direct)',
                quality: '720p',
                mimeType: 'video/mp4',
                url: `/api/youtube/stream?videoId=${encodeURIComponent(videoId)}&quality=720&url=${encodeURIComponent(data.url)}`,
                directUrl: data.url,
                isProxyUrl: true,
              });
              if (!combinedStreamUrl) {
                combinedStreamUrl = data.url;
                combinedQuality = '720p';
              }
            }
          } catch {
            // ignore
          } finally {
            clearTimeout(timer);
          }
        })()
      );
    }

    await Promise.allSettled(mirrorTasks);
  }

  if (subtitles.length === 0) {
    subtitles = await fetchCommunityYouTubeCaptionTracks(videoId);
  }

  // Build final formats list: put working top-level proxy streams first ONLY if a backing URL was found
  const formats: StreamFormatItem[] = [];
  if (bestAudioUrl || combinedStreamUrl) {
    const audioTarget = bestAudioUrl || combinedStreamUrl!;
    formats.push({
      id: `proxy-audio-${videoId}`,
      type: 'audio',
      label: 'High-Quality Audio Stream (Recommended for AI Subtitles)',
      quality: 'High Bitrate Audio',
      mimeType: 'audio/mp4',
      url: `/api/youtube/stream?videoId=${encodeURIComponent(videoId)}&quality=audio&url=${encodeURIComponent(audioTarget)}`,
      directUrl: audioTarget,
      isProxyUrl: true,
    });
  }
  if (combinedStreamUrl || bestVideoOnlyUrl) {
    const videoTarget = combinedStreamUrl || bestVideoOnlyUrl!;
    formats.push({
      id: `proxy-video-720-${videoId}`,
      type: 'combined',
      label: `${combinedQuality || videoQuality || '720p'} Video Stream (Backend Proxy)`,
      quality: combinedQuality || videoQuality || '720p',
      mimeType: 'video/mp4',
      url: `/api/youtube/stream?videoId=${encodeURIComponent(videoId)}&quality=720&url=${encodeURIComponent(videoTarget)}`,
      directUrl: videoTarget,
      isProxyUrl: true,
    });
  }

  for (const df of discoveredFormats) {
    if (!formats.some((f) => f.id === df.id)) {
      formats.push(df);
    }
  }

  if (hlsUrl && !formats.some((f) => f.url === hlsUrl)) {
    formats.push({
      id: `hls-manifest-${videoId}`,
      type: 'combined',
      label: 'HLS Manifest (m3u8)',
      mimeType: 'application/vnd.apple.mpegurl',
      url: hlsUrl,
    });
  }
  if (dashUrl && !formats.some((f) => f.url === dashUrl)) {
    formats.push({
      id: `dash-manifest-${videoId}`,
      type: 'combined',
      label: 'DASH Manifest (mpd)',
      mimeType: 'application/dash+xml',
      url: dashUrl,
    });
  }

  return {
    success: true,
    videoId,
    title,
    dashUrl,
    hlsUrl,
    combinedStreamUrl,
    combinedQuality,
    bestAudioUrl,
    audioBitrate,
    bestVideoOnlyUrl,
    videoQuality,
    subtitles,
    formats,
    duration,
    thumbnailUrl,
    directLinks: {
      cobalt: `https://cobalt.tools/#https://www.youtube.com/watch?v=${videoId}`,
      tenDownloader: `https://10downloader.com/download?v=https://www.youtube.com/watch?v=${videoId}`,
      y2mate: `https://www.sosyoutube.com/watch?v=${videoId}`,
      saveFrom: `https://en.savefrom.net/20/#url=https://www.youtube.com/watch?v=${videoId}`,
      piped: `https://piped.video/watch?v=${videoId}`,
      invidious: `https://inv.nadeko.net/watch?v=${videoId}`,
    },
    ...(formats.length === 0
      ? {
          error:
            'Direct stream links were restricted on this server IP. You can still generate AI Subtitles directly from the YouTube link or use the 1-click downloaders below.',
        }
      : {}),
  };
}

export async function getYouTubeCaptionsServerSide(
  videoId: string,
  targetLanguage?: string
): Promise<any> {
  if (!videoId || !/^[a-zA-Z0-9_-]{11}$/.test(videoId)) {
    return {
      success: false,
      videoId,
      source: 'unavailable',
      requiresTranscription: false,
      reason: 'YOUTUBE_VIDEO_INVALID',
      message: 'Invalid YouTube Video ID format.',
    };
  }

  try {
    const prefCode = normalizeLanguageCode(targetLanguage);
    const ctx = await fetchWatchAndEmbedContext(videoId);
    const playerPayloads = await fetchYouTubePlayerDataCandidates(videoId, ctx);
    let availableTracks = collectYouTubeCaptionTracks(playerPayloads, ctx.captionTracks);
    const metadata =
      playerPayloads.find((payload) => payload?.videoDetails) || playerPayloads[0] || {};

    if (!availableTracks.length) {
      availableTracks = await fetchCommunityYouTubeCaptionTracks(videoId);
    }

    const videoDetails = metadata?.videoDetails || {};
    const title = ctx.title || videoDetails.title || 'YouTube_Video';
    const duration = parseInt(videoDetails.lengthSeconds || '0', 10) || 0;
    const thumbnailUrl =
      videoDetails.thumbnail?.thumbnails?.slice(-1)[0]?.url ||
      `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`;

    const fetchTrackSegments = async (
      trackUrl: string,
      clientName = 'ANDROID_VR',
      tlang?: string
    ): Promise<CaptionSegment[]> => {
      const ua = CLIENT_USER_AGENTS[clientName] || DESKTOP_CHROME_UA;
      const candidateUrls: string[] = [];
      try {
        const parsed = new URL(trackUrl);
        if (parsed.hostname.endsWith('youtube.com') && parsed.pathname.includes('/api/timedtext')) {
          for (const fmt of ['json3', 'srv1', 'vtt', '']) {
            const u = new URL(trackUrl);
            if (fmt) u.searchParams.set('fmt', fmt);
            if (tlang) u.searchParams.set('tlang', tlang);
            candidateUrls.push(u.toString());
          }
        } else {
          candidateUrls.push(trackUrl);
        }
      } catch {
        candidateUrls.push(trackUrl);
      }

      for (const captionUrl of Array.from(new Set(candidateUrls))) {
        const controller = new AbortController();
        const timer = setTimeout(() => controller.abort(), 5000);
        try {
          const subRes = await fetch(captionUrl, {
            headers: {
              'User-Agent': ua,
              Accept: 'text/vtt, application/json, application/xml, text/xml, */*',
              'Accept-Language': 'en-US,en;q=0.9',
              Referer: `https://www.youtube.com/watch?v=${videoId}`,
            },
            signal: controller.signal,
          });
          if (!subRes.ok) continue;
          const rawContent = await subRes.text();
          const segments = parseRawCaptionToSegments(rawContent);
          if (segments.length > 0) return segments;
        } catch {
          // try next format
        } finally {
          clearTimeout(timer);
        }
      }
      return [];
    };

    if (availableTracks.length > 0) {
      const target = String(targetLanguage || '').trim().toLowerCase();
      const languageMatches = (track: YouTubeCaptionTrackCandidate) =>
        Boolean(
          (target &&
            (track.name.toLowerCase().includes(target) ||
              track.code.toLowerCase() === target ||
              track.code.toLowerCase().startsWith(target + '-'))) ||
            (prefCode &&
              (track.code.toLowerCase() === prefCode.toLowerCase() ||
                track.code.toLowerCase().startsWith(prefCode.toLowerCase() + '-')))
        );

      const orderedTracks = [...availableTracks].sort((a, b) => {
        const aMatch = languageMatches(a) ? 1 : 0;
        const bMatch = languageMatches(b) ? 1 : 0;
        if (aMatch !== bMatch) return bMatch - aMatch;
        if (a.isAutoGenerated !== b.isAutoGenerated) return a.isAutoGenerated ? 1 : -1;
        return 0;
      });

      for (const track of orderedTracks) {
        const isExactMatch = !prefCode || languageMatches(track);

        // If user requested a specific target language and YouTube supports tlang auto-translation on this track, try it first
        if (!isExactMatch && prefCode && track.isTranslatable !== false) {
          const translatedSegments = await fetchTrackSegments(
            track.url,
            track.clientName,
            prefCode
          );
          if (translatedSegments.length > 0) {
            const rawSrt = segmentsToSrt(translatedSegments);
            return {
              success: true,
              videoId,
              title,
              source: 'youtube_cc',
              language: `${track.code} → ${prefCode}`,
              isAutoGenerated: track.isAutoGenerated,
              segments: translatedSegments,
              rawSrt,
              duration,
              thumbnailUrl,
              availableTracks,
            };
          }
        }

        const segments = await fetchTrackSegments(track.url, track.clientName);
        if (segments.length > 0) {
          const rawSrt = segmentsToSrt(segments);
          return {
            success: true,
            videoId,
            title,
            source: 'youtube_cc',
            language: track.code,
            isAutoGenerated: track.isAutoGenerated,
            segments,
            rawSrt,
            duration,
            thumbnailUrl,
            availableTracks,
          };
        }
      }
    }

    // Tier 2: Try installed `youtube-transcript` library
    try {
      const transcriptItems = await YoutubeTranscript.fetchTranscript(videoId, {
        lang: prefCode || undefined,
      }).catch(() => YoutubeTranscript.fetchTranscript(videoId));

      if (Array.isArray(transcriptItems) && transcriptItems.length > 0) {
        const maxOffset = Math.max(...transcriptItems.map((i) => Number(i.offset) || 0));
        const isMs = maxOffset > 36000;
        const segments: CaptionSegment[] = transcriptItems
          .map((item) => {
            const rawStart = Number(item.offset) || 0;
            const rawDur = Number(item.duration) || (isMs ? 2000 : 2.0);
            const startSec = isMs ? rawStart / 1000 : rawStart;
            const durSec = isMs ? rawDur / 1000 : rawDur;
            return {
              start: Number(startSec.toFixed(3)),
              end: Number(Math.max(startSec + 0.4, startSec + durSec).toFixed(3)),
              text: String(item.text || '')
                .replace(/&amp;/g, '&')
                .replace(/&#39;/g, "'")
                .replace(/&quot;/g, '"')
                .trim(),
            };
          })
          .filter((s) => s.text.length > 0);

        if (segments.length > 0) {
          const rawSrt = segmentsToSrt(segments);
          return {
            success: true,
            videoId,
            title,
            source: 'youtube_cc',
            language: prefCode || 'en',
            isAutoGenerated: false,
            segments,
            rawSrt,
            duration,
            thumbnailUrl,
            availableTracks,
          };
        }
      }
    } catch {
      // proceed to Tier 3
    }

    // Tier 3: Direct TimedText probing
    const langsToProbe = Array.from(
      new Set([prefCode, 'en', 'en-US', 'id', 'ja', 'ko', 'es'].filter(Boolean) as string[])
    );
    for (const lang of langsToProbe) {
      const probeUrls = [
        `https://www.youtube.com/api/timedtext?v=${videoId}&lang=${lang}&fmt=json3`,
        `https://www.youtube.com/api/timedtext?v=${videoId}&lang=${lang}&kind=asr&fmt=json3`,
        `https://www.youtube.com/api/timedtext?v=${videoId}&lang=${lang}&fmt=srv1`,
        `https://www.youtube.com/api/timedtext?v=${videoId}&lang=${lang}&kind=asr&fmt=srv1`,
      ];
      for (const u of probeUrls) {
        const controller = new AbortController();
        const timer = setTimeout(() => controller.abort(), 3000);
        try {
          const res = await fetch(u, {
            headers: { 'User-Agent': DESKTOP_CHROME_UA },
            signal: controller.signal,
          });
          if (!res.ok) continue;
          const text = await res.text();
          const segments = parseRawCaptionToSegments(text);
          if (segments.length > 0) {
            return {
              success: true,
              videoId,
              title,
              source: 'youtube_cc',
              language: lang,
              isAutoGenerated: u.includes('kind=asr'),
              segments,
              rawSrt: segmentsToSrt(segments),
              duration,
              thumbnailUrl,
              availableTracks,
            };
          }
        } catch {
          // ignore
        } finally {
          clearTimeout(timer);
        }
      }
    }

    return {
      success: true,
      videoId,
      title,
      source: 'unavailable',
      requiresTranscription: true,
      reason: availableTracks.length ? 'CAPTIONS_RETRIEVAL_BLOCKED' : 'CAPTIONS_NOT_AVAILABLE',
      message: availableTracks.length
        ? 'YouTube caption tracks were found, but timed-text URLs were restricted. Click "Generate YouTube SRT Subtitles" to transcribe with Gemini Multimodal AI.'
        : 'No YouTube closed-caption tracks were uploaded for this video. Click "Generate YouTube SRT Subtitles" to transcribe with Gemini Multimodal AI.',
      duration,
      thumbnailUrl,
      availableTracks,
    };
  } catch (err: any) {
    console.error('[YouTube Caption Service Error]', err);
    return {
      success: false,
      videoId,
      source: 'unavailable',
      requiresTranscription: true,
      reason: 'SERVER_RETRIEVAL_FAILED',
      message: err?.message || 'Server caption retrieval encountered an error.',
    };
  }
}

function escapeHtml(str: string): string {
  return String(str || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function buildInjectedProxyHeadScript(finalUrl: string, ua: string): string {
  const safeFinalUrlJson = JSON.stringify(finalUrl);
  const safeUaJson = JSON.stringify(ua || '');
  return `<script data-mv-proxy="1">
(function() {
  var CURRENT_URL = ${safeFinalUrlJson};
  var CURRENT_UA = ${safeUaJson};

  function toProxyUrl(rawUrl) {
    if (!rawUrl || typeof rawUrl !== 'string') return null;
    var trimmed = rawUrl.trim();
    if (!trimmed || trimmed.startsWith('#') || trimmed.startsWith('javascript:') || trimmed.startsWith('mailto:') || trimmed.startsWith('tel:') || trimmed.startsWith('data:') || trimmed.startsWith('blob:')) {
      return null;
    }
    if (trimmed.startsWith('/api/proxy?') || trimmed.startsWith('/api/browser/')) {
      return trimmed;
    }
    try {
      var abs = new URL(trimmed, CURRENT_URL).toString();
      if (!/^https?:\\/\\//i.test(abs)) return null;
      return '/api/proxy?url=' + encodeURIComponent(abs) + (CURRENT_UA ? '&ua=' + encodeURIComponent(CURRENT_UA) : '');
    } catch (e) {
      return null;
    }
  }

  function notifyParent(url, title) {
    try {
      if (window.parent && window.parent !== window) {
        window.parent.postMessage({
          type: 'MV_BROWSER_NAVIGATE',
          url: url || CURRENT_URL,
          title: title || document.title || CURRENT_URL
        }, '*');
      }
    } catch (e) {}
  }

  window.addEventListener('DOMContentLoaded', function() {
    notifyParent(CURRENT_URL, document.title);
  });
  window.addEventListener('load', function() {
    notifyParent(CURRENT_URL, document.title);
  });

  document.addEventListener('click', function(e) {
    var el = e.target && e.target.closest ? e.target.closest('a[href]') : null;
    if (!el) return;
    var rawHref = el.getAttribute('href');
    if (!rawHref || rawHref.startsWith('#') || rawHref.startsWith('javascript:')) return;
    var proxied = toProxyUrl(rawHref);
    if (proxied) {
      e.preventDefault();
      e.stopPropagation();
      try {
        var resolvedAbs = new URL(rawHref, CURRENT_URL).toString();
        notifyParent(resolvedAbs, el.textContent ? el.textContent.trim().slice(0, 60) : resolvedAbs);
      } catch (_) {}
      window.location.href = proxied;
    }
  }, true);

  document.addEventListener('submit', function(e) {
    var form = e.target;
    if (!form || form.tagName !== 'FORM') return;
    var rawAction = form.getAttribute('action') || CURRENT_URL;
    var method = (form.getAttribute('method') || 'GET').toUpperCase();
    try {
      var absAction = new URL(rawAction, CURRENT_URL);
      if (method === 'GET') {
        e.preventDefault();
        e.stopPropagation();
        var formData = new FormData(form);
        formData.forEach(function(value, key) {
          if (typeof value === 'string') {
            absAction.searchParams.set(key, value);
          }
        });
        var finalTarget = absAction.toString();
        notifyParent(finalTarget, 'Search: ' + finalTarget);
        window.location.href = toProxyUrl(finalTarget) || finalTarget;
      } else {
        form.setAttribute('action', toProxyUrl(absAction.toString()) || rawAction);
      }
    } catch (_) {}
  }, true);

  var origOpen = window.open;
  window.open = function(url, target, features) {
    if (url && typeof url === 'string') {
      var proxied = toProxyUrl(url);
      if (proxied) {
        try {
          var abs = new URL(url, CURRENT_URL).toString();
          notifyParent(abs, abs);
        } catch (_) {}
        window.location.href = proxied;
        return window;
      }
    }
    return origOpen ? origOpen.call(window, url, target, features) : null;
  };
})();
</script>`;
}

export function extractSearchQueryIfSearchEngineUrl(rawUrl: string): string | null {
  try {
    const u = new URL(rawUrl);
    const host = u.hostname.toLowerCase();
    const isGoogle = /^(www\.|m\.)?google\.[a-z.]+$/i.test(host);
    const isBing = /^(www\.)?bing\.com$/i.test(host);
    const isDdg = /^(www\.|start\.)?duckduckgo\.com$/i.test(host);
    const isYahoo = host.includes('search.yahoo.com');

    if (isGoogle || isBing || isDdg || isYahoo) {
      const q = u.searchParams.get('q') || u.searchParams.get('p');
      if (q && q.trim()) return q.trim();
      if (u.pathname === '/' || u.pathname === '' || u.pathname === '/search' || u.pathname === '/webhp') {
        return '__HOME__';
      }
    }
  } catch {
    // ignore
  }
  return null;
}

