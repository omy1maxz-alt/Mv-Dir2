export function extractVideoId(rawUrl: string): string | null {
  if (!rawUrl) return null;
  const clean = String(rawUrl).trim();
  if (/^[a-zA-Z0-9_-]{11}$/.test(clean)) return clean;
  const match = clean.match(
    /(?:youtube\.com\/(?:[^\/]+\/.+\/|(?:v|e(?:mbed)?|shorts|live)\/|.*[?&]v=)|youtu\.be\/)([^"&?\/\s]{11})/i
  );
  return match ? match[1] : null;
}

export function getMatchingUserAgentForStreamUrl(streamUrl: string): string {
  try {
    const parsed = new URL(streamUrl);
    const clientParam = (parsed.searchParams.get('c') || '').toUpperCase();
    if (clientParam && CLIENT_USER_AGENTS[clientParam]) {
      return CLIENT_USER_AGENTS[clientParam];
    }
    if (parsed.hostname.includes('googlevideo.com')) {
      return CLIENT_USER_AGENTS.ANDROID_VR;
    }
  } catch {
    // ignore
  }
  return DESKTOP_CHROME_UA;
}

