export function normalizeLanguageCode(lang?: string): string | null {
  if (!lang) return null;
  const clean = lang.trim().toLowerCase();
  if (
    !clean ||
    clean === 'original' ||
    clean === 'auto-detect' ||
    clean === 'auto' ||
    clean === 'verbatim'
  ) {
    return null;
  }
  if (LANGUAGE_NAME_TO_CODE[clean]) return LANGUAGE_NAME_TO_CODE[clean];
  if (/^[a-z]{2,3}(-[a-z0-9]+)?$/i.test(clean)) return clean;
  for (const [name, code] of Object.entries(LANGUAGE_NAME_TO_CODE)) {
    if (clean.includes(name)) return code;
  }
  return null;
}

