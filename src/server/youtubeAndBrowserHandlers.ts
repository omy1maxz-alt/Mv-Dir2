export function collectYouTubeCaptionTracks(
  payloads: any[],
  extraTracks?: any[]
): YouTubeCaptionTrackCandidate[] {
  const unique = new Map<string, YouTubeCaptionTrackCandidate>();

  const registerList = (rawTracks: any[], clientName = 'WEB') => {
    if (!Array.isArray(rawTracks)) return;
    for (const track of rawTracks) {
      const baseUrl = typeof track?.baseUrl === 'string' ? track.baseUrl.trim() : '';
      if (!baseUrl) continue;
      const code = String(track.languageCode || 'und');
      const name =
        track.name?.simpleText ||
        (Array.isArray(track.name?.runs)
          ? track.name.runs.map((r: any) => r?.text || '').join('')
          : '') ||
        code ||
        'Captions';
      const isAutoGenerated = track.kind === 'asr';
      const key = `${code}|${isAutoGenerated}`;
      if (!unique.has(key)) {
        unique.set(key, {
          name,
          code,
          url: baseUrl,
          isAutoGenerated,
          mimeType: 'text/vtt',
          isTranslatable: track.isTranslatable !== false,
          clientName,
        });
      }
    }
  };

  if (Array.isArray(extraTracks)) {
    registerList(extraTracks, 'WATCH_HTML');
  }
  for (const payload of payloads) {
    const rawTracks = payload?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
    registerList(rawTracks, payload?._clientName || 'ANDROID_VR');
  }

  return Array.from(unique.values());
}

