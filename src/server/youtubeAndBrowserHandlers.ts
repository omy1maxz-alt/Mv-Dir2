export async function handleProxiedWebRequest(
  req: any,
  res: any,
  parsedUrl: URL
): Promise<void> {
  const targetUrl = parsedUrl.searchParams.get('url');
  const customUa = parsedUrl.searchParams.get('ua') || '';

  if (!targetUrl) {
    res.statusCode = 400;
    res.setHeader('Content-Type', 'text/plain; charset=utf-8');
    res.end('Missing url parameter');
    return;
  }

  const searchQuery = extractSearchQueryIfSearchEngineUrl(targetUrl);
  if (searchQuery) {
    const html = await renderBrowserSearchHtml(searchQuery, customUa);
    res.statusCode = 200;
    res.setHeader('Content-Type', 'text/html; charset=utf-8');
    res.setHeader('Access-Control-Allow-Origin', '*');
    res.end(html);
    return;
  }

  try {
    const u = new URL(targetUrl);
    if (
      (u.hostname.includes('youtube.com') && u.pathname === '/watch' && u.searchParams.get('v')) ||
      u.hostname === 'youtu.be'
    ) {
      const vid = u.searchParams.get('v') || u.pathname.replace(/^\//, '').split('/')[0];
      if (vid && /^[a-zA-Z0-9_-]{11}$/.test(vid)) {
        res.statusCode = 302;
        res.setHeader('Location', `https://www.youtube.com/embed/${vid}?autoplay=1&rel=0`);
        res.end();
        return;
      }
    }
  } catch {
    // ignore
  }

  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 15000);

  try {
    const effectiveUa = customUa || req.headers['user-agent'] || DESKTOP_CHROME_UA;
    const headers: Record<string, string> = {
      'User-Agent': effectiveUa,
      Accept:
        req.headers['accept'] ||
        'text/html,application/xhtml+xml,application/xml;q=0.9,image/avif,image/webp,*/*;q=0.8',
      'Accept-Language': req.headers['accept-language'] || 'en-US,en;q=0.9',
    };

    const response = await fetch(targetUrl, {
      method: req.method === 'POST' ? 'POST' : 'GET',
      headers,
      redirect: 'follow',
      signal: controller.signal,
    });

    const finalUrl = response.url || targetUrl;
    const contentType = response.headers.get('content-type') || 'text/html; charset=utf-8';

    res.setHeader('Content-Type', contentType);
    res.setHeader('Access-Control-Allow-Origin', '*');
    res.setHeader('Access-Control-Allow-Methods', 'GET, POST, HEAD, OPTIONS');

    if (contentType.includes('text/html') || contentType.includes('application/xhtml+xml')) {
      let html = await response.text();
      html = html.replace(/<meta[^>]+http-equiv=["']?Content-Security-Policy["']?[^>]*>/gi, '');
      html = html.replace(/<meta[^>]+http-equiv=["']?X-Frame-Options["']?[^>]*>/gi, '');

      const finalUrlObj = new URL(finalUrl);
      const baseHref = new URL('.', finalUrlObj).toString();
      const injectedTags = `<base href="${escapeHtml(baseHref)}">${buildInjectedProxyHeadScript(
        finalUrl,
        customUa
      )}`;

      if (/<head[^>]*>/i.test(html)) {
        html = html.replace(/<head([^>]*)>/i, `<head$1>${injectedTags}`);
      } else if (/<html[^>]*>/i.test(html)) {
        html = html.replace(/<html([^>]*)>/i, `<html$1><head>${injectedTags}</head>`);
      } else {
        html = injectedTags + html;
      }

      res.statusCode = response.status;
      res.end(html);
    } else {
      const buffer = await response.arrayBuffer();
      res.statusCode = response.status;
      res.end(Buffer.from(buffer));
    }
  } catch (err: any) {
    res.statusCode = 200;
    res.setHeader('Content-Type', 'text/html; charset=utf-8');
    res.end(`<!DOCTYPE html>
<html>
<head><meta charset="utf-8"><title>Unable to Load Page</title></head>
<body style="font-family:-apple-system,BlinkMacSystemFont,sans-serif;padding:28px;background:#0e0e16;color:#f1f5f9;">
  <div style="max-width:560px;margin:20px auto;background:#161622;border:1px solid rgba(255,255,255,0.12);border-radius:16px;padding:24px;">
    <h3 style="margin-top:0;color:#2dd4bf;">Could not reach ${escapeHtml(targetUrl)}</h3>
    <p style="color:#94a3b8;font-size:13px;line-height:1.5;">${escapeHtml(
      err?.message || 'The remote server closed the connection or timed out.'
    )}</p>
    <div style="display:flex;gap:10px;margin-top:16px;">
      <a href="/api/browser/search?q=${encodeURIComponent(
        targetUrl
      )}" style="background:#0d9488;color:#fff;text-decoration:none;padding:8px 14px;border-radius:10px;font-size:12px;font-weight:700;">Search Web Instead</a>
      <a href="${escapeHtml(
        targetUrl
      )}" target="_blank" rel="noopener noreferrer" style="background:rgba(255,255,255,0.1);color:#fff;text-decoration:none;padding:8px 14px;border-radius:10px;font-size:12px;font-weight:700;">Open in External Browser ↗</a>
    </div>
  </div>
</body>
</html>`);
  } finally {
    clearTimeout(timeout);
  }
}

async function readJsonBody(req: any): Promise<any> {
  if (req.body && typeof req.body === 'object') return req.body;
  return new Promise((resolve) => {
    let raw = '';
    req.on('data', (chunk: any) => {
      raw += chunk;
    });
    req.on('end', () => {
      try {
        resolve(raw ? JSON.parse(raw) : {});
      } catch {
        resolve({});
      }
    });
    req.on('error', () => resolve({}));
  });
}

function sendJson(res: any, statusCode: number, payload: any) {
  res.statusCode = statusCode;
  res.setHeader('Content-Type', 'application/json; charset=utf-8');
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.end(JSON.stringify(payload));
}

/**
 * Connect/Express compatible middleware for handling:
 * - /api/proxy
 * - /api/browser/search
 * - /api/youtube/extract & /api/resolve-stream
 * - /api/youtube/stream
 * - /api/youtube/captions
 * - /api/youtube/caption-tracks
 * - /api/youtube/manifests
 * - /api/youtube/subtitles
 */
export async function handleYouTubeAndBrowserApiMiddleware(
  req: any,
  res: any,
  next: () => void
): Promise<void> {
  if (!req.url) {
    next();
    return;
  }

  const parsedUrl = new URL(req.url, 'http://localhost:3000');
  const pathname = parsedUrl.pathname;

  // 1. Browser Web Proxy
  if (pathname === '/api/proxy') {
    await handleProxiedWebRequest(req, res, parsedUrl);
    return;
  }

  // 2. Built-in Tab Browser Search Engine
  if (pathname === '/api/browser/search') {
    const q = parsedUrl.searchParams.get('q') || '';
    const ua = parsedUrl.searchParams.get('ua') || '';
    const html = await renderBrowserSearchHtml(q, ua);
    res.statusCode = 200;
    res.setHeader('Content-Type', 'text/html; charset=utf-8');
    res.setHeader('Access-Control-Allow-Origin', '*');
    res.end(html);
    return;
  }

  // 3. YouTube Extraction API
  if (pathname === '/api/youtube/extract' || pathname === '/api/resolve-stream') {
    try {
      const body = req.method === 'POST' ? await readJsonBody(req) : {};
      const rawUrl =
        body.url || parsedUrl.searchParams.get('url') || '';
      const directVideoId =
        body.videoId ||
        parsedUrl.searchParams.get('videoId') ||
        parsedUrl.searchParams.get('v') ||
        '';
      const videoId = directVideoId || extractVideoId(rawUrl);

      if (!videoId) {
        sendJson(res, 400, { error: 'Valid YouTube URL or videoId is required.' });
        return;
      }

      const result = await resolveYouTubeVideoServerSide(videoId);
      sendJson(res, 200, result);
    } catch (err: any) {
      sendJson(res, 500, { error: err?.message || 'Internal server extraction error.' });
    }
    return;
  }

  // 4. YouTube Stream Proxy
  if (pathname === '/api/youtube/stream') {
    try {
      const rawDirectUrl = parsedUrl.searchParams.get('url') || '';
      const isYoutubeWatchPage = /^(https?:\/\/)?(www\.|m\.)?(youtube\.com\/(watch|shorts|embed|v)|youtu\.be\/)/i.test(rawDirectUrl);
      const directUrl = isYoutubeWatchPage ? '' : rawDirectUrl;
      const videoId =
        parsedUrl.searchParams.get('v') ||
        parsedUrl.searchParams.get('videoId') ||
        (isYoutubeWatchPage ? extractVideoId(rawDirectUrl) || '' : '');
      const quality = parsedUrl.searchParams.get('quality') || 'audio';

      let targetStreamUrl: string | null = directUrl || null;

      if (!targetStreamUrl && videoId) {
        const resolved = await resolveYouTubeVideoServerSide(videoId);
        if (quality === 'audio') {
          targetStreamUrl = resolved.bestAudioUrl || resolved.combinedStreamUrl || null;
        } else {
          targetStreamUrl = resolved.combinedStreamUrl || resolved.bestVideoOnlyUrl || null;
        }
      }

      if (!targetStreamUrl) {
        sendJson(res, 404, {
          error:
            'Stream URL could not be resolved on this server IP. Use one of the verified direct downloaders or AI YouTube Transcription.',
        });
        return;
      }

      const upstreamUa = getMatchingUserAgentForStreamUrl(targetStreamUrl);
      const upstreamHeaders: Record<string, string> = {
        'User-Agent': upstreamUa,
        Accept: '*/*',
        Referer: 'https://www.youtube.com/',
        Origin: 'https://www.youtube.com',
      };
      if (req.headers.range) {
        upstreamHeaders['Range'] = req.headers.range;
      }

      let sourceRes = await fetch(targetStreamUrl, {
        headers: upstreamHeaders,
        redirect: 'follow',
      });

      // If direct URL expired or returned 403, re-resolve once using videoId
      if (!sourceRes.ok && sourceRes.status !== 206 && videoId && directUrl) {
        const refreshed = await resolveYouTubeVideoServerSide(videoId);
        const fallbackUrl =
          quality === 'audio'
            ? refreshed.bestAudioUrl || refreshed.combinedStreamUrl
            : refreshed.combinedStreamUrl || refreshed.bestVideoOnlyUrl;
        if (fallbackUrl && fallbackUrl !== targetStreamUrl) {
          sourceRes = await fetch(fallbackUrl, {
            headers: {
              ...upstreamHeaders,
              'User-Agent': getMatchingUserAgentForStreamUrl(fallbackUrl),
            },
            redirect: 'follow',
          });
        }
      }

      if (!sourceRes.ok && sourceRes.status !== 206) {
        sendJson(res, sourceRes.status, {
          error: `Upstream stream returned HTTP ${sourceRes.status} (${sourceRes.statusText}).`,
        });
        return;
      }

      const contentType =
        sourceRes.headers.get('content-type') ||
        (quality === 'audio' ? 'audio/mp4' : 'video/mp4');
      const contentLength = sourceRes.headers.get('content-length');
      const contentRange = sourceRes.headers.get('content-range');

      const ext = contentType.includes('audio')
        ? contentType.includes('webm')
          ? 'webm'
          : 'm4a'
        : 'mp4';

      const headers: Record<string, string> = {
        'Content-Type': contentType,
        'Accept-Ranges': 'bytes',
        'Access-Control-Allow-Origin': '*',
        'Content-Disposition': `attachment; filename="youtube_${videoId || 'media'}.${ext}"`,
      };
      if (contentLength) headers['Content-Length'] = contentLength;
      if (contentRange) headers['Content-Range'] = contentRange;

      res.writeHead(sourceRes.status === 206 ? 206 : 200, headers);

      if (sourceRes.body) {
        const reader = sourceRes.body.getReader();
        while (true) {
          const { done, value } = await reader.read();
          if (done) break;
          res.write(Buffer.from(value));
        }
        res.end();
      } else {
        const arrayBuffer = await sourceRes.arrayBuffer();
        res.end(Buffer.from(arrayBuffer));
      }
    } catch (err: any) {
      if (!res.headersSent) {
        sendJson(res, 500, { error: err?.message || 'Streaming proxy failed.' });
      } else {
        res.end();
      }
    }
    return;
  }

  // 5. YouTube Captions Structured API
  if (pathname === '/api/youtube/captions') {
    try {
      const body = req.method === 'POST' ? await readJsonBody(req) : {};
      const rawUrl = parsedUrl.searchParams.get('url') || body.url || '';
      const rawVideoId =
        parsedUrl.searchParams.get('videoId') ||
        parsedUrl.searchParams.get('v') ||
        body.videoId ||
        '';
      const targetLang =
        parsedUrl.searchParams.get('targetLang') || body.targetLang || '';
      const videoId = rawVideoId || extractVideoId(rawUrl);

      if (!videoId) {
        sendJson(res, 400, {
          success: false,
          videoId: '',
          source: 'unavailable',
          requiresTranscription: false,
          reason: 'YOUTUBE_VIDEO_INVALID',
          message: 'A valid YouTube URL or videoId is required.',
        });
        return;
      }

      const captionResult = await getYouTubeCaptionsServerSide(videoId, targetLang);
      sendJson(res, 200, captionResult);
    } catch (err: any) {
      sendJson(res, 500, {
        success: false,
        source: 'unavailable',
        requiresTranscription: true,
        reason: 'SERVER_RETRIEVAL_FAILED',
        message: err?.message || 'Internal server error resolving captions.',
      });
    }
    return;
  }

  // 6. YouTube Caption Tracks Inventory API
  if (pathname === '/api/youtube/caption-tracks') {
    try {
      const body = req.method === 'POST' ? await readJsonBody(req) : {};
      const rawUrl = parsedUrl.searchParams.get('url') || body.url || '';
      const rawVideoId =
        parsedUrl.searchParams.get('videoId') ||
        parsedUrl.searchParams.get('v') ||
        body.videoId ||
        '';
      const videoId = rawVideoId || extractVideoId(rawUrl);
      if (!videoId || !/^[a-zA-Z0-9_-]{11}$/.test(videoId)) {
        sendJson(res, 400, {
          success: false,
          videoId: videoId || '',
          tracks: [],
          message: 'A valid YouTube URL or video ID is required.',
        });
        return;
      }

      const ctx = await fetchWatchAndEmbedContext(videoId);
      const payloads = await fetchYouTubePlayerDataCandidates(videoId, ctx);
      let tracks = collectYouTubeCaptionTracks(payloads, ctx.captionTracks);
      if (!tracks.length) tracks = await fetchCommunityYouTubeCaptionTracks(videoId);
      const metadata = payloads.find((p) => p?.videoDetails) || payloads[0] || {};
      sendJson(res, 200, {
        success: true,
        videoId,
        title: ctx.title || metadata?.videoDetails?.title || 'YouTube_Video',
        duration: parseInt(metadata?.videoDetails?.lengthSeconds || '0', 10) || 0,
        thumbnailUrl:
          metadata?.videoDetails?.thumbnail?.thumbnails?.slice(-1)[0]?.url ||
          `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`,
        tracks,
      });
    } catch (err: any) {
      sendJson(res, 502, {
        success: false,
        tracks: [],
        message: err?.message || 'Could not discover YouTube caption tracks.',
      });
    }
    return;
  }

  // 7. YouTube Manifests Discovery API
  if (pathname === '/api/youtube/manifests') {
    try {
      const body = req.method === 'POST' ? await readJsonBody(req) : {};
      const rawUrl = parsedUrl.searchParams.get('url') || body.url || '';
      const rawVideoId =
        parsedUrl.searchParams.get('videoId') ||
        parsedUrl.searchParams.get('v') ||
        body.videoId ||
        '';
      const videoId = rawVideoId || extractVideoId(rawUrl);
      if (!videoId || !/^[a-zA-Z0-9_-]{11}$/.test(videoId)) {
        sendJson(res, 400, {
          success: false,
          videoId: videoId || '',
          hlsUrl: null,
          dashUrl: null,
          message: 'A valid YouTube URL or video ID is required.',
        });
        return;
      }

      const ctx = await fetchWatchAndEmbedContext(videoId);
      const [playerPayloads, community] = await Promise.all([
        fetchYouTubePlayerDataCandidates(videoId, ctx),
        fetchCommunityYouTubeManifestCandidates(videoId),
      ]);
      const playerData = playerPayloads.map((p) => p?.streamingData || {});
      const hlsUrl =
        playerData.map((s) => s.hlsManifestUrl).find((u: unknown) => typeof u === 'string' && u) ||
        community.map((c) => c.hlsUrl).find((u) => !!u) ||
        null;
      const dashUrl =
        playerData
          .map((s) => s.dashManifestUrl)
          .find((u: unknown) => typeof u === 'string' && u) ||
        community.map((c) => c.dashUrl).find((u) => !!u) ||
        null;
      const metadata = playerPayloads.find((p) => p?.videoDetails) || playerPayloads[0] || {};
      const title = ctx.title || metadata?.videoDetails?.title || 'YouTube_Video';
      const duration = parseInt(metadata?.videoDetails?.lengthSeconds || '0', 10) || 0;
      const thumbnailUrl =
        metadata?.videoDetails?.thumbnail?.thumbnails?.slice(-1)[0]?.url ||
        `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`;

      sendJson(res, 200, {
        success: true,
        videoId,
        title,
        duration,
        thumbnailUrl,
        hlsUrl,
        dashUrl,
        sources: {
          playerClients: playerPayloads.length,
          communityProviders: community.length,
        },
        message:
          hlsUrl || dashUrl
            ? 'Available manifest URLs were discovered.'
            : 'No HLS/DASH manifest URL was exposed by the available YouTube player clients or fallback providers.',
      });
    } catch (err: any) {
      sendJson(res, 502, {
        success: false,
        hlsUrl: null,
        dashUrl: null,
        message: err?.message || 'YouTube manifest lookup failed.',
      });
    }
    return;
  }

  // 8. YouTube Subtitles Direct Proxy (auto-converts XML/JSON3/VTT into clean SRT/VTT)
  if (pathname === '/api/youtube/subtitles') {
    try {
      const subtitleUrl = parsedUrl.searchParams.get('url') || '';
      const format = (parsedUrl.searchParams.get('format') || 'srt').toLowerCase();
      if (!subtitleUrl) {
        sendJson(res, 400, { error: 'Subtitle URL is required.' });
        return;
      }

      // Try json3 / srv1 / vtt variants if it's a youtube timedtext URL
      const urlsToTry = [subtitleUrl];
      try {
        const u = new URL(subtitleUrl);
        if (u.hostname.endsWith('youtube.com') && u.pathname.includes('/api/timedtext')) {
          const j3 = new URL(subtitleUrl);
          j3.searchParams.set('fmt', 'json3');
          urlsToTry.unshift(j3.toString());
        }
      } catch {
        // ignore
      }

      let rawText = '';
      for (const candidateUrl of Array.from(new Set(urlsToTry))) {
        const controller = new AbortController();
        const timer = setTimeout(() => controller.abort(), 5000);
        try {
          const subRes = await fetch(candidateUrl, {
            headers: {
              'User-Agent': CLIENT_USER_AGENTS.ANDROID_VR,
              Accept: 'text/vtt, application/json, application/xml, text/xml, */*',
              Referer: 'https://www.youtube.com/',
            },
            signal: controller.signal,
          });
          if (subRes.ok) {
            const txt = await subRes.text();
            if (txt && txt.trim()) {
              rawText = txt;
              break;
            }
          }
        } catch {
          // try next
        } finally {
          clearTimeout(timer);
        }
      }

      if (!rawText) {
        res.statusCode = 404;
        res.setHeader('Content-Type', 'text/plain; charset=utf-8');
        res.end('Failed to fetch subtitle content from upstream.');
        return;
      }

      const segments = parseRawCaptionToSegments(rawText);
      res.statusCode = 200;
      res.setHeader('Access-Control-Allow-Origin', '*');
      if (segments.length > 0) {
        if (format === 'vtt') {
          res.setHeader('Content-Type', 'text/vtt; charset=utf-8');
          res.end(segmentsToVtt(segments));
        } else {
          res.setHeader('Content-Type', 'text/plain; charset=utf-8');
          res.end(segmentsToSrt(segments));
        }
      } else {
        res.setHeader('Content-Type', 'text/plain; charset=utf-8');
        res.end(rawText);
      }
    } catch (err: any) {
      sendJson(res, 500, { error: err?.message || 'Subtitle proxy failed.' });
    }
    return;
  }

  next();
}
