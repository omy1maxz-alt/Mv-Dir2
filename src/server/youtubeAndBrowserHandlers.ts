function extractBalancedJsonObject(source: string, markerIndex: number): any | null {
  const braceStart = source.indexOf('{', markerIndex);
  if (braceStart === -1) return null;
  let depth = 0;
  let inString = false;
  let escaped = false;
  for (let i = braceStart; i < source.length; i++) {
    const ch = source[i];
    if (inString) {
      if (escaped) escaped = false;
      else if (ch === '\\') escaped = true;
      else if (ch === '"') inString = false;
      continue;
    }
    if (ch === '"') inString = true;
    else if (ch === '{') depth++;
    else if (ch === '}') {
      depth--;
      if (depth === 0) {
        try {
          return JSON.parse(source.slice(braceStart, i + 1));
        } catch {
          return null;
        }
      }
    }
  }
  return null;
}

export async function fetchWatchAndEmbedContext(videoId: string): Promise<WatchPageContext> {
  const ctx: WatchPageContext = {};

  const watchPromise = (async () => {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 4500);
    try {
      const res = await fetch(
        `https://www.youtube.com/watch?v=${videoId}&bpctr=9999999999&has_verified=1&hl=en`,
        {
          headers: {
            'User-Agent': DESKTOP_CHROME_UA,
            'Accept-Language': 'en-US,en;q=0.9',
            Cookie: 'CONSENT=YES+cb; PREF=hl=en',
          },
          signal: controller.signal,
        }
      );
      if (!res.ok) return;
      const html = await res.text();

      const visitorMatch = html.match(/"VISITOR_DATA"\s*:\s*"([^"]+)"/);
      if (visitorMatch) ctx.visitorData = visitorMatch[1];

      const stsMatch =
        html.match(/"STS"\s*:\s*(\d+)/) || html.match(/signatureTimestamp"\s*:\s*(\d+)/);
      if (stsMatch) ctx.signatureTimestamp = parseInt(stsMatch[1], 10);

      const keyMatch = html.match(/"INNERTUBE_API_KEY"\s*:\s*"([^"]+)"/);
      if (keyMatch) ctx.apiKey = keyMatch[1];

      const markers = [
        'ytInitialPlayerResponse = ',
        'ytInitialPlayerResponse=',
        '"ytInitialPlayerResponse":',
      ];
      for (const marker of markers) {
        const idx = html.indexOf(marker);
        if (idx !== -1) {
          const parsed = extractBalancedJsonObject(html, idx + marker.length);
          if (parsed) {
            ctx.playerResponse = parsed;
            if (parsed?.videoDetails?.title) ctx.title = parsed.videoDetails.title;
            if (parsed?.videoDetails?.author) ctx.author = parsed.videoDetails.author;
            const tracks = parsed?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
            if (Array.isArray(tracks) && tracks.length > 0) {
              ctx.captionTracks = tracks;
            }
            break;
          }
        }
      }

      if (!ctx.captionTracks) {
        const capIdx = html.indexOf('"captionTracks":');
        if (capIdx !== -1) {
          const bracketStart = html.indexOf('[', capIdx);
          if (bracketStart !== -1) {
            let depth = 0;
            let inStr = false;
            let esc = false;
            for (let i = bracketStart; i < Math.min(html.length, bracketStart + 35000); i++) {
              const ch = html[i];
              if (inStr) {
                if (esc) esc = false;
                else if (ch === '\\') esc = true;
                else if (ch === '"') inStr = false;
                continue;
              }
              if (ch === '"') inStr = true;
              else if (ch === '[') depth++;
              else if (ch === ']') {
                depth--;
                if (depth === 0) {
                  try {
                    const parsedTracks = JSON.parse(html.slice(bracketStart, i + 1));
                    if (Array.isArray(parsedTracks) && parsedTracks.length > 0) {
                      ctx.captionTracks = parsedTracks;
                    }
                  } catch {
                    // ignore
                  }
                  break;
                }
              }
            }
          }
        }
      }
    } catch {
      // ignore
    } finally {
      clearTimeout(timer);
    }
  })();

  const embedPromise = (async () => {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 4000);
    try {
      const res = await fetch(`https://www.youtube.com/embed/${videoId}?hl=en`, {
        headers: {
          'User-Agent': DESKTOP_CHROME_UA,
          'Accept-Language': 'en-US,en;q=0.9',
          Referer: 'https://www.youtube.com/',
        },
        signal: controller.signal,
      });
      if (!res.ok) return;
      const html = await res.text();
      if (!ctx.visitorData) {
        const visitorMatch = html.match(/"VISITOR_DATA"\s*:\s*"([^"]+)"/);
        if (visitorMatch) ctx.visitorData = visitorMatch[1];
      }
      if (!ctx.signatureTimestamp) {
        const stsMatch =
          html.match(/"STS"\s*:\s*(\d+)/) || html.match(/signatureTimestamp"\s*:\s*(\d+)/);
        if (stsMatch) ctx.signatureTimestamp = parseInt(stsMatch[1], 10);
      }
    } catch {
      // ignore
    } finally {
      clearTimeout(timer);
    }
  })();

  await Promise.allSettled([watchPromise, embedPromise]);
  return ctx;
}

